let language = 'en';
try { if (localStorage.getItem('jomei-language') === 'de') language = 'de'; } catch { /* English is the default. */ }
let bindings = [];
let initialized = false;
export const getLanguage = () => language;
export const locale = () => language === 'de' ? 'de-DE' : 'en-GB';
export const time = value => new Date(value).toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit' });
export function t(english, values = {}) {
  const text = language === 'de' ? (GERMAN[english] ?? english) : english;
  return text.replace(/\{([a-zA-Z]+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export function errorMessage(error) {
  if (!error) return '';
  if (error.code === 'rate-limit') return t('GitHub rate limit reached. Try again after {time}.', { time: time(error.retryAt) });
  if (error.code === 'not-found') return t('Not available on GitHub yet.');
  if (error.code === 'http') return t('GitHub is currently unavailable ({status}).', { status: error.status });
  if (error.code === 'invalid-request') return t('Invalid GitHub request.');
  return t('Could not connect to GitHub. Please try again.');
}
export function setLanguage(value, { persist = true } = {}) {
  language = value === 'de' ? 'de' : 'en';
  if (persist) { try { localStorage.setItem('jomei-language', language); } catch { /* Optional storage. */ } }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = language;
    for (const { node, attribute, original, key } of bindings) {
      const value = original.replace(key, t(key));
      if (attribute) node.setAttribute(attribute, value);
      else node.textContent = value;
    }
    document.querySelectorAll('[data-language-select]').forEach(select => { select.value = language; });
    document.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
  }
}
export function initLanguage() {
  if (initialized) return;
  initialized = true;
  const walker = document.createTreeWalker(document.documentElement, 4);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.parentElement?.closest('script, style, noscript, [data-language-select]')) continue;
    const key = node.textContent.trim();
    if (Object.hasOwn(GERMAN, key)) bindings.push({ node, key, original: node.textContent });
  }
  document.querySelectorAll('[aria-label], [placeholder], meta[content]').forEach(node => {
    for (const attribute of ['aria-label', 'placeholder', 'content']) {
      const original = node.getAttribute(attribute);
      if (original && Object.hasOwn(GERMAN, original)) bindings.push({ node, attribute, original, key: original });
    }
  });
  document.querySelectorAll('[data-language-select]').forEach(select => {
    select.addEventListener('change', () => setLanguage(select.value));
  });
  setLanguage(language, { persist: false });
}
