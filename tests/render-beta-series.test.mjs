import test from 'node:test';
import assert from 'node:assert/strict';
import { renderPage } from './helpers/render.mjs';

test('version selection isolates downloads, search and counts and survives refresh and language changes', async context => {
  const run = (id, head_branch, created_at) => ({ id, head_branch, created_at, status: 'completed', conclusion: 'success', event: 'push', head_sha: `abc${id}`, display_title: `Change ${id}`, html_url: `https://github.com/JoMei9019-real/AirPort-RTW/actions/runs/${id}` });
  const runs = [run(1, '1.0.0-beta', '2026-10-01'), run(2, '1.0.0-beta', '2026-10-24'), run(3, 'beta-2.0.0', '2026-10-07'), run(5, '1.0.0-beta', '2026-10-25'), run(6, '1.0.0-beta', '2026-10-26')];
  const artifacts = runs.map((run, index) => ({ id: run.id * 10, workflow_run: { id: run.id }, name: `AirPortRTW-${['1.0.2-beta.4', '1.1.0-beta.7', '2.0.0-beta.17', '1.3.0-beta.1', '1.3.0-beta.2'][index]}`, created_at: run.created_at, expires_at: '2099-01-01', size_in_bytes: 1000 }));
  let fail = false;
  let stable = 'v1.2.1';
  const page = await renderPage(context, 'beta/index.html', url => {
    if (fail) throw new Error('offline');
    if (url.endsWith('/releases/latest')) return { tag_name: stable, prerelease: false, draft: false };
    return url.includes('/actions/artifacts?') ? { artifacts } : { workflow_runs: runs };
  });
  const filters = page.element('#version-filters');
  const select = version => filters.trigger('click', { target: { closest: () => ({ dataset: { version } }) } });
  const html = () => page.element('#build-list').innerHTML;
  const settle = async () => { for (let i = 0; i < 10; i++) await new Promise(setImmediate); };
  assert.match(page.element('#series-heading').textContent, /1\.3\.0/);
  assert.equal(page.element('#series-release').hidden, true);
  assert.doesNotMatch(filters.innerHTML, /data-version="1\.(0\.2|1\.0)"/);
  assert.match(html(), /AirPortRTW-1\.3\.0-beta\.1/);
  assert.match(html(), /AirPortRTW-1\.3\.0-beta\.2/);
  assert.equal(page.element('#build-range').textContent, '2 of 2 builds · Newest first');
  page.element('#build-search').value = 'beta.1';
  page.element('#build-search').trigger('input');
  assert.match(html(), /artifacts\/50/);
  assert.doesNotMatch(html(), /artifacts\/60/);
  select('2.0.0');
  assert.equal(page.element('#build-search').value, '');
  assert.match(html(), /artifacts\/30/);
  assert.doesNotMatch(html(), /artifacts\/(50|60)/);
  page.language.setLanguage('de');
  assert.match(page.element('#series-heading').textContent, /2\.0\.0 Beta-Builds/);
  assert.match(filters.innerHTML, /BETA-REIHE/);
  assert.match(html(), /Artifact herunterladen/);
  page.language.setLanguage('en');
  page.element('#refresh-builds').trigger('click');
  await settle();
  assert.match(page.element('#series-heading').textContent, /2\.0\.0/);
  assert.match(html(), /artifacts\/30/);
  // A new version is discovered without adding a hardcoded tab.
  runs.push(run(4, 'beta-3.0.0', '2026-10-25'));
  artifacts.push({ ...artifacts[0], id: 40, workflow_run: { id: 4 }, name: 'AirPortRTW-3.0.0-beta.1' });
  page.element('#refresh-builds').trigger('click');
  await settle();
  assert.match(filters.innerHTML, /data-version="3.0.0"/);
  assert.match(page.element('#series-heading').textContent, /2\.0\.0/);
  select('3.0.0');
  assert.match(html(), /artifacts\/40/);
  stable = 'v3.0.0';
  page.element('#refresh-builds').trigger('click');
  await settle();
  assert.doesNotMatch(filters.innerHTML, /data-version=/);
  assert.match(html(), /No current beta builds available/);
  assert.equal(page.element('#series-release').hidden, false);
  fail = true;
  page.element('#refresh-builds').trigger('click');
  await settle();
  assert.match(html(), /No current beta builds available/);
  assert.match(page.element('#beta-status').textContent, /Cached data/);
});
